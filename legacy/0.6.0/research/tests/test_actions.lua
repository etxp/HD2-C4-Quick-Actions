local function pending_during_refill()
    local s=make('rounds')
    s.u32(s.rounds_state+4,0)
    s.step(0);s.step(20,'DEPLOY');s.step(40,'DEPLOY')
    equal(#s.calls,4);equal(s.controller.pending.action,'DEPLOY')
    s.complete();s.step(100)
    return s
end
test('queued Deploy survives native completion until the real chamber becomes ready',function()
    local s=pending_during_refill()
    equal(s.controller.lock,nil);equal(s.controller.pending.action,'DEPLOY')
    equal(s.count('pending_waiting'),1);equal(s.count('action_rejected'),0)
    for t=200,400,100 do s.step(t) end
    equal(#s.calls,4);equal(s.count('pending_waiting'),1)
    s.u32(s.rounds_state+0x10,55);s.put(s.rounds_runtime+0x10,'\0');s.step(500)
    equal(#s.calls,8);equal(s.controller.pending,nil);equal(s.calls[5][2],521)
end)
test('repeat requests during refill neither grow the pending slot nor refresh its deadline',function()
    local s=pending_during_refill()
    s.step(200,'DEPLOY');s.step(400,'DETONATE')
    equal(s.controller.pending.action,'DEPLOY');equal(s.controller.pending.at,40)
    equal(s.count('action_queued'),1);equal(s.count('action_rejected'),2);equal(#s.calls,4)
    s.step(1600);equal(s.controller.pending,nil)
    s.u32(s.rounds_state+0x10,55);s.put(s.rounds_runtime+0x10,'\0');s.step(1700)
    equal(#s.calls,4)
end)
test('weapon switch, focus, disarm, mouse and failed context also clear a refill-waiting request',function()
    for _,kind in ipairs({'weapon','focus','capture','mouse','read'}) do
        local s=pending_during_refill()
        if kind=='weapon' then s.u32(s.state+0x1c,1)
        elseif kind=='read' then s.memory[s.rounds_state]=nil end
        s.step(200,nil,kind~='capture',kind~='focus',kind=='mouse')
