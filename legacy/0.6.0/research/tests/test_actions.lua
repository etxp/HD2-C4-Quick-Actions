local passed=0
local function equal(a,b) assert(a==b,tostring(a)..' ~= '..tostring(b)) end
local function test(name,f)
    local ok,err=pcall(f);assert(ok,name..': '..tostring(err))
    passed=passed+1;print('PASS '..name)
end
local function make(ammo_path)
    local s=fixture(ammo_path)
    s.backend=backend.new(s.api,reader,base,s.layout,s.bind)
    s.events={}
    s.controller=controller.new(s.backend,function(kind,fields)
        if s.log_failure then return false end
        s.events[#s.events+1]={kind=kind,fields=fields};return true
    end)
    function s.step(now,action,armed,allowed,mouse)
        s.controller.step(armed~=false,now,{deploy=action=='DEPLOY' or action=='BOTH',
            detonate=action=='DETONATE' or action=='BOTH',allowed=allowed~=false,mouse=mouse})
    end
    function s.count(kind)
        local n=0;for _,r in ipairs(s.events) do if r.kind==kind then n=n+1 end end;return n
    end
    return s
end
